// Expo config plugin: silence remaining Xcode warnings on iOS 26 builds.
//
// Two layers of mutation, both required:
//
//   A. Podfile post_install — runs at `pod install` time. Normalizes every pod
//      to deployment target 16.0 and silences vendored Pods-side warnings.
//      WARNING_CFLAGS receives explicit `-Wno-nullability-completeness` and
//      `-Wno-incomplete-umbrella` so the diagnostics are not emitted while
//      pod modules are being compiled and serialized into Clang `.pcm`
//      module-cache files (Xcode replays cached diagnostics on consumers
//      even when the consumer's flags would silence them).
//
//   B. Main Xcode project (SudokuEvolved.xcodeproj) — runs at `expo prebuild`
//      time. Silences warnings that are emitted by the *consumer* (the app
//      target) when it imports vendored headers — these can't be stopped from
//      the pod side. Specifically:
//        - CLANG_WARN_INCOMPLETE_UMBRELLA = NO  (kills React.framework /
//          SDWebImageWebPCoder umbrella validation noise on every consumer
//          compile)
//        - OTHER_CFLAGS += -Wno-nullability-completeness  (kills the
//          "Pointer is missing a nullability type specifier" cascade
//          coming from ExpoModulesCore + ExpoFileSystem public headers
//          when compiled directly as C/Obj-C)
//        - OTHER_SWIFT_FLAGS += -Xcc -Wno-nullability-completeness
//                              -Xcc -Wno-incomplete-umbrella
//          The app's `import Expo` / `import React` paths route through
//          Swift's Clang importer, so the C-side -Wno- flags must be
//          forwarded with -Xcc to suppress the same diagnostics there.
//          Existing Swift flags (-D EXPO_CONFIGURATION_DEBUG / _RELEASE)
//          are preserved.
//        - OTHER_LDFLAGS deduped  (drops the duplicated -lc++ that the
//          autogenerated app target ships when the inherited Pods xcconfig
//          already provides it)
//
// The app target's own first-party warnings (its Swift / Obj-C source) are
// NOT silenced. Only categories that originate from imported pod headers.
//
// Idempotent: re-running `expo prebuild --clean` regenerates everything and
// this plugin re-applies cleanly.

const { withDangerousMod, withXcodeProject } = require('@expo/config-plugins');
const fs = require('fs');
const path = require('path');

const APP_TARGET_NAME = 'SudokuEvolved';

// ---------------------------------------------------------------------------
// Layer A: Podfile post_install injection
// ---------------------------------------------------------------------------

const BEGIN = '# === BEGIN with-pod-warnings (auto-generated) ===';
const END = '# === END with-pod-warnings ===';

const INJECTION = `
${BEGIN}
    # Normalize every pod to deployment target 16.0 and silence vendored
    # third-party warnings. App target (SudokuEvolved) keeps its warnings on.
    suppressed_warning_flags = ['-Wno-nullability-completeness', '-Wno-incomplete-umbrella']
    installer.pods_project.targets.each do |target|
      is_app_target = target.name == '${APP_TARGET_NAME}'
      target.build_configurations.each do |config|
        # A: deployment target floor
        config.build_settings['IPHONEOS_DEPLOYMENT_TARGET'] = '16.0'
        # B: umbrella header drift in RN 0.81 prebuilt React-Core
        config.build_settings['CLANG_WARN_INCOMPLETE_UMBRELLA'] = 'NO'
        # C: cross-pod non-modular includes
        config.build_settings['CLANG_ALLOW_NON_MODULAR_INCLUDES_IN_FRAMEWORK_MODULES'] = 'YES'
        # D: doxygen comment noise in vendored Obj-C
        config.build_settings['CLANG_WARN_DOCUMENTATION_COMMENTS'] = 'NO'

        # E + F: blanket-suppress on third-party only — keep app warnings live
        unless is_app_target
          config.build_settings['GCC_WARN_INHIBIT_ALL_WARNINGS'] = 'YES'
          config.build_settings['SWIFT_SUPPRESS_WARNINGS'] = 'YES'
        end

        # I: Push -Wno- flags directly into every pod's WARNING_CFLAGS so
        # the two diagnostics are not emitted while pod modules compile
        # into .pcm files. GCC_WARN_INHIBIT_ALL_WARNINGS silences live
        # emission on third-party pods, but Xcode's module-cache replay
        # path can still surface diagnostics serialized into the .pcm
        # before that setting was honored. Adding direct -Wno- flags
        # makes the suppression unambiguous at module-emission time.
        existing = config.build_settings['WARNING_CFLAGS']
        warning_cflags =
          if existing.is_a?(Array)
            existing.dup
          elsif existing.nil? || existing.to_s.strip.empty?
            []
          else
            existing.to_s.split(/\s+/).reject(&:empty?)
          end
        warning_cflags.unshift('$(inherited)') unless warning_cflags.include?('$(inherited)')
        suppressed_warning_flags.each do |flag|
          warning_cflags << flag unless warning_cflags.include?(flag)
        end
        config.build_settings['WARNING_CFLAGS'] = warning_cflags

        # H: dedupe -lc++ etc. when prebuilt RN piles them in (Array form)
        ldflags = config.build_settings['OTHER_LDFLAGS']
        if ldflags.is_a?(Array)
          config.build_settings['OTHER_LDFLAGS'] = ldflags.uniq
        end
      end

      # G: Hermes / CocoaPods copy phases — declare always-out-of-date so
      # Xcode 16+ stops nagging about missing output dependencies.
      target.build_phases.each do |phase|
        next unless phase.respond_to?(:shell_script)
        next if phase.name.nil?
        if phase.name.include?('[CP]') || phase.name.include?('Hermes')
          phase.always_out_of_date = '1'
        end
      end
    end
${END}
`;

function withPodfilePostInstall(config) {
  return withDangerousMod(config, [
    'ios',
    async (cfg) => {
      const podfile = path.join(cfg.modRequest.platformProjectRoot, 'Podfile');
      let src = fs.readFileSync(podfile, 'utf8');

      // Idempotent: strip any prior injection before re-inserting
      const a = src.indexOf(BEGIN);
      const b = src.indexOf(END);
      if (a !== -1 && b !== -1) {
        src =
          src.slice(0, a).trimEnd() +
          '\n' +
          src.slice(b + END.length).trimStart();
      }

      // Inject AFTER the react_native_post_install(...) call inside post_install
      const anchor =
        ':ccache_enabled => ccache_enabled?(podfile_properties),\n    )';
      if (!src.includes(anchor)) {
        throw new Error(
          'with-pod-warnings: react_native_post_install anchor not found in Podfile',
        );
      }
      src = src.replace(anchor, anchor + '\n' + INJECTION);

      fs.writeFileSync(podfile, src);
      return cfg;
    },
  ]);
}

// ---------------------------------------------------------------------------
// Layer B: Main project (SudokuEvolved.xcodeproj) build settings
// ---------------------------------------------------------------------------

const NULLABILITY_FLAG = '-Wno-nullability-completeness';
const INCOMPLETE_UMBRELLA_FLAG = '-Wno-incomplete-umbrella';

// Pairs to forward through Swift's Clang importer via -Xcc. Each pair is
// kept together as a single token so we can dedupe by substring presence.
const SWIFT_XCC_PAIRS = [
  `-Xcc ${NULLABILITY_FLAG}`,
  `-Xcc ${INCOMPLETE_UMBRELLA_FLAG}`,
];

/**
 * Normalize an OTHER_CFLAGS / OTHER_LDFLAGS value coming out of xcode-project
 * into an array of token strings. xcode-project may return:
 *   - undefined (unset)
 *   - a single string ("$(inherited)")
 *   - an array of strings (["$(inherited)", "-lc++"])
 * Strings are kept quoted exactly as Xcode wants them.
 */
function asFlagArray(value) {
  if (value === undefined || value === null) return ['"$(inherited)"'];
  if (Array.isArray(value)) return value.slice();
  if (typeof value === 'string') return [value];
  return ['"$(inherited)"'];
}

/** Drop any token equal to `flag` (with or without surrounding quotes). */
function withoutFlag(arr, flag) {
  const quoted = `"${flag}"`;
  return arr.filter((t) => t !== flag && t !== quoted);
}

/** True if the array contains the flag (in any quoting). */
function hasFlag(arr, flag) {
  const quoted = `"${flag}"`;
  return arr.includes(flag) || arr.includes(quoted);
}

/**
 * Append additional flags to OTHER_SWIFT_FLAGS while preserving any flags
 * the project already has (notably -D EXPO_CONFIGURATION_DEBUG / _RELEASE).
 *
 * xcode-project stores OTHER_SWIFT_FLAGS as either:
 *   - undefined
 *   - a quoted string: '"$(inherited) -D EXPO_CONFIGURATION_DEBUG"'
 *   - an array of token strings
 *
 * We normalize to a single quoted string so the resulting pbxproj keeps the
 * conventional `OTHER_SWIFT_FLAGS = "$(inherited) ..."` shape.
 */
function appendSwiftFlags(existing, additions) {
  let inner;
  if (existing === undefined || existing === null) {
    inner = '$(inherited)';
  } else if (Array.isArray(existing)) {
    inner = existing
      .map((token) => {
        const s = String(token);
        return s.startsWith('"') && s.endsWith('"') && s.length >= 2
          ? s.slice(1, -1)
          : s;
      })
      .join(' ');
  } else {
    inner = String(existing);
    if (inner.startsWith('"') && inner.endsWith('"') && inner.length >= 2) {
      inner = inner.slice(1, -1);
    }
  }

  if (!inner.includes('$(inherited)')) {
    inner = inner.length === 0 ? '$(inherited)' : `$(inherited) ${inner}`;
  }

  for (const piece of additions) {
    if (!inner.includes(piece)) {
      inner = `${inner} ${piece}`;
    }
  }

  return `"${inner.trim()}"`;
}

function withMainProjectSettings(config) {
  return withXcodeProject(config, (cfg) => {
    const proj = cfg.modResults;
    const configurations = proj.pbxXCBuildConfigurationSection();

    // Only mutate configurations belonging to the SudokuEvolved app target.
    // Skip Pods aggregate configs and the project-level configs.
    Object.keys(configurations).forEach((key) => {
      const c = configurations[key];
      if (!c || typeof c !== 'object') return;
      if (!c.buildSettings) return;

      // Heuristic: app target configs have PRODUCT_NAME and a bundle id, and
      // their PRODUCT_NAME or INFOPLIST_FILE references SudokuEvolved.
      const settings = c.buildSettings;
      const productName = (settings.PRODUCT_NAME || '').toString();
      const infoPlist = (settings.INFOPLIST_FILE || '').toString();
      const isAppTarget =
        productName.includes(APP_TARGET_NAME) ||
        infoPlist.includes(APP_TARGET_NAME);
      if (!isAppTarget) return;

      // 1. Silence umbrella validation when consuming React.framework + others.
      settings.CLANG_WARN_INCOMPLETE_UMBRELLA = 'NO';

      // 2. Add -Wno-nullability-completeness to OTHER_CFLAGS for the C/Obj-C
      //    consumer compile path.
      let cflags = asFlagArray(settings.OTHER_CFLAGS);
      if (!hasFlag(cflags, NULLABILITY_FLAG)) {
        cflags.push(`"${NULLABILITY_FLAG}"`);
      }
      settings.OTHER_CFLAGS = cflags;

      // 3. Forward the same C-side suppressions through the Swift Clang
      //    importer via -Xcc so Swift translation units (the entire app
      //    target is Swift) don't re-emit the diagnostics when importing
      //    Obj-C modules from ExpoModulesCore / ExpoFileSystem / ExpoAudio
      //    / React-Core-prebuilt / SDWebImageWebPCoder.
      settings.OTHER_SWIFT_FLAGS = appendSwiftFlags(
        settings.OTHER_SWIFT_FLAGS,
        SWIFT_XCC_PAIRS,
      );

      // 4. Dedupe OTHER_LDFLAGS — most importantly drop the duplicated -lc++
      //    that's already provided by the inherited Pods xcconfig.
      let ldflags = asFlagArray(settings.OTHER_LDFLAGS);
      // Remove explicit -lc++ from the app target. The Pods xcconfig provides
      // it via $(inherited), so keeping it here is a guaranteed duplicate.
      ldflags = withoutFlag(ldflags, '-lc++');
      // Generic dedupe for any other repeats.
      const seen = new Set();
      ldflags = ldflags.filter((t) => {
        if (seen.has(t)) return false;
        seen.add(t);
        return true;
      });
      settings.OTHER_LDFLAGS = ldflags;
    });

    return cfg;
  });
}

// ---------------------------------------------------------------------------

module.exports = function withPodWarnings(config) {
  config = withPodfilePostInstall(config);
  config = withMainProjectSettings(config);
  return config;
};
